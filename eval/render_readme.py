"""Write the live scoreboard into README.md, between markers.

The README used to carry a hand-typed results table with an as-of date. That
is a claim which rots: the counts climb every day, horizons cross the ranking
gate, and the file quietly starts lying about what the system can defend.

So the table is generated from eval/metrics.json on every pipeline run and
committed by the Action. The verdict wording is derived, not written — when a
horizon crosses MIN_SCORED the sentence changes by itself, with nobody
reading this repo.

Only the region between the markers is touched. Everything else in the README
is prose and stays hand-written.

    uv run python eval/render_readme.py        # patch README.md in place
    uv run python eval/render_readme.py --check  # exit 1 if it would change
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).parents[1]
README = ROOT / "README.md"
METRICS = Path(__file__).parent / "metrics.json"

START = "<!-- APAW:SCOREBOARD:START -->"
END = "<!-- APAW:SCOREBOARD:END -->"

# Kept in the generated text so a reader never has to guess what "certified"
# means, and so the number moves if backtest.py's gate ever moves.
_GATE_NOTE = ("A horizon with fewer than {gate} scored forecasts is shown with "
              "its count and **not ranked** — small-n verdicts are noise, not "
              "skill.")


def _verdict(v: dict, gate: int) -> str:
    ahead = v["mae_model"] < v["mae_best_baseline"]
    if v["enough_data"]:
        return "**APAW**" if ahead else "baseline wins"
    if ahead:
        return f"ahead, needs {gate - v['n']} more"
    return f"behind, needs {gate - v['n']} more"


def render(metrics: dict, today: date | None = None) -> str:
    per_h = metrics["per_horizon"]
    hs = sorted(per_h, key=int)
    gate = per_h[hs[0]]["min_scored"]
    today = today or date.today()

    lines = [
        START,
        "",
        _GATE_NOTE.format(gate=gate),
        "",
        "| Horizon | APAW | Persistence | Best baseline | n | Verdict |",
        "|---|---|---|---|---|---|",
    ]
    for h in hs:
        v = per_h[h]
        ahead = v["mae_model"] < v["mae_best_baseline"]
        mae = f"**{v['mae_model']:.3f}**" if ahead else f"{v['mae_model']:.3f}"
        lines.append(
            f"| +{h}d | {mae} | {v['mae_persistence']:.3f} | "
            f"{v['mae_best_baseline']:.3f} {v['best_baseline']} | {v['n']} | "
            f"{_verdict(v, gate)} |")

    certified = [h for h in hs if per_h[h]["enough_data"]
                 and per_h[h]["mae_model"] < per_h[h]["mae_best_baseline"]]
    ahead_all = [h for h in hs
                 if per_h[h]["mae_model"] < per_h[h]["mae_best_baseline"]]
    provisional = [h for h in ahead_all if h not in certified]
    losing = [h for h in hs if h not in ahead_all]

    lines += ["", f"*Generated by `eval/render_readme.py` on {today}. "
                  "Regenerated on every pipeline run — the "
                  "[live dashboard](https://zeref538.github.io/apaw/) and this "
                  "table cannot drift apart.*", ""]

    # The claim, derived from the numbers rather than asserted.
    if len(certified) == len(hs):
        lines.append(
            f"**APAW beats both naive baselines at all {len(hs)} horizons, and "
            f"every one of them clears the {gate}-forecast bar.** This is the "
            "full claim: no horizon is resting on a small sample.")
    elif ahead_all and not losing:
        need = min(gate - per_h[h]["n"] for h in provisional)
        lines.append(
            f"**APAW is ahead of both naive baselines at all {len(hs)} "
            f"horizons.** {len(certified)} of {len(hs)} clear the {gate}-forecast "
            f"bar and are ranked; the rest are ahead but still counting — the "
            f"next one needs {need} more scored forecasts. Being unranked is a "
            "statement about sample size, not about accuracy.")
    else:
        lines.append(
            f"**APAW is ahead at {len(ahead_all)} of {len(hs)} horizons** "
            f"({len(certified)} of them ranked). Horizons where a naive "
            f"baseline still wins are listed above as losses, not hidden: "
            f"{', '.join('+' + h + 'd' for h in losing)}.")

    src = metrics.get("by_rain_source") or {}
    if {"era5_proxy", "forecast"} <= set(src):
        lines += ["", (
            f"Split by rain source: {src['era5_proxy']['mae_model']:.3f} m for "
            f"ERA5-proxy rows (n={src['era5_proxy']['n']}) against "
            f"{src['forecast']['mae_model']:.3f} m for real archived forecasts "
            f"(n={src['forecast']['n']}). Those groups differ by **era** as "
            "well as by rain source, so the gap is not a clean measure of what "
            "the shortcut is worth. It is published because the shortcut "
            "exists, not as a finding.")]

    lines += ["", END]
    return "\n".join(lines)


def patch(text: str, block: str) -> str:
    if START not in text or END not in text:
        raise SystemExit(
            f"README.md is missing the {START} / {END} markers; refusing to "
            "guess where the scoreboard goes.")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the README is out of date, change nothing")
    args = ap.parse_args()

    metrics = json.loads(METRICS.read_text(encoding="utf-8"))
    current = README.read_text(encoding="utf-8")
    updated = patch(current, render(metrics))

    if args.check:
        if current != updated:
            print("README scoreboard is stale; run eval/render_readme.py",
                  file=sys.stderr)
            return 1
        print("README scoreboard is current")
        return 0

    if current == updated:
        print("README scoreboard unchanged")
        return 0
    README.write_text(updated, encoding="utf-8")
    print("README scoreboard updated")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
